function inGameAI.onPause ( v )
--------------------------------------------------------------------------------
	
	--
	-- Write your code here, using 'this' as current AI instance.
	--
    this.inPause ( v )
    local hScene = application.getCurrentUserScene ( )
	scene.setPaused ( hScene, v )
    if (v) then
        music.setVolume ( hScene, 0.1, 0.5 )
    else
        music.setVolume ( hScene, 0.3, 0.5 )
    end
--------------------------------------------------------------------------------
end
