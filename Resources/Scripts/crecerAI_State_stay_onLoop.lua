function crecerAI.stay_onLoop ( )
--------------------------------------------------------------------------------
	
	--
	-- Write your code here, using 'this' as current AI instance.
	--
	local dt=application.getLastFrameTime ( )
    local ct=this.time ( )
    ct=ct-dt
    if (ct<=0) then
        this.dead ( )
    else
        this.time ( ct )
    end
--------------------------------------------------------------------------------
end
